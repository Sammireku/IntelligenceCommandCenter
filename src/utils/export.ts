import { SweepPayload } from '../types.js';

export function exportSweepAsJson(sweep: SweepPayload) {
  const blob = new Blob([JSON.stringify(sweep, null, 2)], { type: 'application/json' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `milz-sentry-intelligence-${sweep.sweepId}.json`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

