export function exportSweepAsCsvByCategory(sweep: SweepPayload, category: string) {
  const rows: string[][] = [];
  
  if (category === 'alerts' || category === 'all') {
    rows.push(['Category', 'Alert ID', 'Tier', 'Domain', 'Title', 'Summary', 'Timestamp', 'Source URL']);
    sweep.alerts.forEach((alert) => {
      rows.push([
        'Alert',
        alert.id,
        alert.tier,
        alert.domain,
        alert.title,
        alert.summary,
        alert.timestamp,
        alert.sourceUrl || ''
      ]);
    });
  }
  
  if (category === 'geospatial' || category === 'all') {
    if (category !== 'all') {
      rows.push(['Category', 'Entity ID', 'Location/Place', 'Metric Value', 'Additional Details', 'Timestamp']);
    }
    // Earthquakes
    sweep.geospatial.data.earthquakes.items.forEach((eq) => {
      rows.push([
        'Geospatial - Earthquake',
        eq.id,
        eq.place,
        `M${eq.mag.toFixed(1)}`,
        `Depth: ${eq.coordinates[2]}km, Tsunami: ${eq.tsunami ? 'Yes' : 'No'}`,
        new Date(eq.time).toISOString()
      ]);
    });
    // Thermal/Fires
    const fireAnomalies = sweep.geospatial.data.thermalAnomalies?.items || sweep.geospatial.data.fireAnomalies || [];
    fireAnomalies.forEach((fire) => {
      rows.push([
        'Geospatial - Wildfire',
        fire.id,
        fire.region,
        `FRP: ${fire.frp} MW`,
        `Brightness: ${fire.brightness}K, Confidence: ${fire.confidence}`,
        fire.acqDate
      ]);
    });
    // Disaster Feed
    sweep.geospatial.data.disasterFeed?.items.forEach((tweet) => {
      rows.push([
        'Geospatial - OSINT Dispatch',
        tweet.id,
        tweet.location?.name || '',
        tweet.disasterType,
        tweet.text,
        tweet.timestamp
      ]);
    });
  }

  if (category === 'markets' || category === 'all') {
    if (category !== 'all') {
      rows.push(['Category', 'Symbol', 'Name', 'Price', '24h Change', 'Description/Metrics']);
    }
    sweep.markets.data.tickers.forEach((ticker) => {
      rows.push([
        'Markets - Ticker',
        ticker.symbol,
        ticker.name,
        ticker.price.toString(),
        `${ticker.change24h}%`,
        ticker.volume24h ? `Vol: ${ticker.volume24h}` : ''
      ]);
    });
    sweep.markets.data.macro.forEach((m) => {
      rows.push([
        'Markets - Macro Indicator',
        m.code,
        m.name,
        m.value.toString(),
        m.trend,
        m.description
      ]);
    });
  }

  if (category === 'infrastructure' || category === 'all') {
    if (category !== 'all') {
      rows.push(['Category', 'ID/MMSI/ICAO', 'System / Asset Name', 'Status / Squawk', 'Detailed Description', 'Timestamp']);
    }
    // CISA KEV
    sweep.infrastructure.data.cisaKev.recentAdded.forEach((kev) => {
      rows.push([
        'Infrastructure - CISA KEV',
        kev.cveID,
        `${kev.vendorProject} ${kev.product}`,
        kev.knownRansomwareCampaignUse === 'Known' ? 'Ransomware Tracked' : 'Nominal Vuln',
        kev.shortDescription,
        kev.dateAdded
      ]);
    });
    // Flights
    sweep.infrastructure.data.airTraffic.emergencySquawks.forEach((f) => {
      rows.push([
        'Infrastructure - Flight Squawk',
        f.icao24,
        `${f.callsign} (${f.aircraftType || 'AIRCRAFT'})`,
        f.squawkType,
        `Altitude: ${f.altitudeFt}ft, Velocity: ${f.velocityKnots}kts, Heading: ${f.heading}°`,
        f.lastContact
      ]);
    });
    // Vessels
    sweep.infrastructure.data.maritime.trackedVessels.forEach((v) => {
      rows.push([
        'Infrastructure - Maritime Vessel',
        v.mmsi,
        v.vesselName,
        v.vesselType,
        `Flag: ${v.flag}, Speed: ${v.speedKnots}kts, Course: ${v.courseDegrees}°, Risk: ${v.riskRating}`,
        new Date().toISOString()
      ]);
    });
  }

  if (category === 'health' || category === 'all') {
    if (category !== 'all') {
      rows.push(['Category', 'ID / Pathogen', 'Source / Journal', 'Alert / Threat Level', 'Summary Details', 'Date']);
    }
    sweep.health.data.papers.forEach((p) => {
      rows.push([
        'Health - Paper',
        p.id,
        p.journal,
        p.threatLevel,
        p.title,
        p.pubDate
      ]);
    });
    sweep.health.data.outbreaks.forEach((o) => {
      rows.push([
        'Health - Outbreak',
        o.id,
        o.region,
        o.alertLevel,
        `${o.pathogen}: ${o.details}`,
        o.date
      ]);
    });
  }

  const csvContent = rows.map(e => e.map(val => `"${val.replace(/"/g, '""')}"`).join(",")).join("\n");
  const blob = new Blob([csvContent], { type: 'text/csv;charset=utf-8;' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.setAttribute('href', url);
  a.setAttribute('download', `milz-sentry-${category}-data-${sweep.sweepId}.csv`);
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

